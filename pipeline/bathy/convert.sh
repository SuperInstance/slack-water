#!/usr/bin/env bash
# convert.sh — turn a real sounding export into shared/bathy/<name>.json.
#
# The standalone luau CLI cannot read files, so this script embeds the input
# into a generated wrapper script (with a long-bracket level that cannot occur
# in the data) and lets luau do the parsing, gridding and JSON encoding.
# See docs/BATHYMETRY.md for the full workflow.
set -euo pipefail

ORIG_PWD="$PWD"
cd "$(dirname "$0")" # pipeline/bathy
export PATH="$HOME/.local/bin:$PATH"

usage() {
	cat <<'USAGE'
usage: pipeline/bathy/convert.sh INPUT [options]

options:
  --units m|ft|fm        REQUIRED. Depth units of the input file. Never guessed.
  --surveyed             Operator assertion that the input is real survey data.
                         Off by default; output then carries surveyed:false.
  --cell METRES          Grid cell size in metres (default 50).
  --radius CELLS         Sounding search radius in cells (default 3).
  --coords geographic|projected
                         Input columns are lon/lat degrees or metres. Default:
                         detected and reported in the output.
  --anchor-lon V --anchor-lat V
                         Real-world coordinate that maps to world origin (0,0).
                         Default: centre of the survey's own bounds.
  --studs-per-metre V    World scale (default 1).
  --depth-sign down|up   Positive depths (default) or positive elevations.
  --name NAME            Output name (default: input file name minus extension).
  --source "TEXT"        Free-text source description, recorded verbatim.
  --out FILE             Output path (default shared/bathy/<name>.json).
  --timestamp ISO        Pinned convertedAt timestamp, for reproducible output.
USAGE
}

die() { echo "convert.sh: $*" >&2; exit 1; }

INPUT=""
OUT=""
ARGS=()

VALUE_FLAGS="--units|--cell|--radius|--coords|--anchor-lon|--anchor-lat|--studs-per-metre|--depth-sign|--name|--source|--timestamp|--source-file"

while [ $# -gt 0 ]; do
	case "$1" in
	--help | -h)
		usage
		exit 0
		;;
	--out)
		[ $# -ge 2 ] || die "--out needs a value"
		OUT="$2"
		shift 2
		;;
	--out=*)
		OUT="${1#--out=}"
		shift
		;;
	--surveyed)
		ARGS+=("--surveyed")
		shift
		;;
	--*)
		ARGS+=("$1")
		if [[ "$1" != --*=* && "$1" =~ ^($VALUE_FLAGS)$ ]]; then
			[ $# -ge 2 ] || die "$1 needs a value"
			ARGS+=("$2")
			shift
		fi
		shift
		;;
	-*)
		die "unknown option $1 (see --help)"
		;;
	*)
		[ -z "$INPUT" ] || die "two input files given: '$INPUT' and '$1'"
		INPUT="$1"
		shift
		;;
	esac
done

[ -n "$INPUT" ] || {
	usage
	die "no input file given"
}
case "$INPUT" in
/*) ;;
*) INPUT="$ORIG_PWD/$INPUT" ;;
esac
[ -f "$INPUT" ] || die "input file not found: $INPUT"

# Default name from the file: sitka-sound.xyz -> sitka-sound
NAME=""
i=0
while [ $i -lt ${#ARGS[@]} ]; do
	if [ "${ARGS[$i]}" = "--name" ]; then
		NAME="${ARGS[$((i + 1))]}"
	elif [[ "${ARGS[$i]}" == --name=* ]]; then
		NAME="${ARGS[$i]#--name=}"
	fi
	i=$((i + 1))
done
if [ -z "$NAME" ]; then
	NAME="$(basename "$INPUT")"
	NAME="${NAME%.*}"
	NAME="${NAME// /-}"
fi
[ -n "$OUT" ] || OUT="$ORIG_PWD/shared/bathy/$NAME.json"

# Tell the luau side which file it is converting (recorded in provenance), and
# carry the derived name into the JSON (appended last so a user --name still
# works — later flags win in the parser).
ARGS+=("--source-file" "$INPUT" "--name" "$NAME")

mkdir -p "$(dirname "$OUT")"

# Pick a long-bracket level whose closing token cannot appear anywhere in the
# input file or in any argument value, so arbitrary data embeds safely.
LEVEL=0
while :; do
	EQ=""
	[ "$LEVEL" -gt 0 ] && EQ="$(printf '=%.0s' $(seq 1 "$LEVEL"))"
	CLOSER="]$EQ]"
	if grep -qF -- "$CLOSER" "$INPUT"; then
		LEVEL=$((LEVEL + 1))
		continue
	fi
	BAD=0
	for a in "${ARGS[@]}"; do
		case "$a" in
		*"$CLOSER"*) BAD=1 ;;
		esac
	done
	[ "$BAD" -eq 0 ] && break
	LEVEL=$((LEVEL + 1))
done
OPEN="[$EQ["

WRAPPER=".bathy-run.$$.luau"
trap 'rm -f "$WRAPPER" "$WRAPPER.err"' EXIT

{
	echo "-- generated by convert.sh — do not edit"
	echo "local INPUT_TEXT = $OPEN"
	cat "$INPUT"
	echo ""
	echo "$CLOSER"
	echo "local argv = {}"
	for a in "${ARGS[@]}"; do
		echo "table.insert(argv, $OPEN$a$CLOSER)"
	done
	echo 'local out = require("./cli").run(INPUT_TEXT, argv)'
	echo 'print(out)'
} >"$WRAPPER"

if ! luau "$WRAPPER" >"$OUT.tmp" 2>"$WRAPPER.err"; then
	rm -f "$OUT.tmp"
	echo "convert.sh: conversion failed:" >&2
	sed 's/^/  /' "$WRAPPER.err" >&2
	exit 1
fi
mv "$OUT.tmp" "$OUT"

BYTES=$(wc -c <"$OUT")
echo "convert.sh: wrote $OUT ($BYTES bytes)"
echo "convert.sh: name=$NAME — check the provenance block before trusting it:"
echo "  grep -o '\"surveyed\":[a-z]*' \"$OUT\" | head -1"
